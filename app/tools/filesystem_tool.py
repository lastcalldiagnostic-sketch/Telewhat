from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List

from app.tools.base_tool import BaseTool
from app.utils import ensure_directory


class FilesystemTool(BaseTool):
    name = "filesystem"

    def execute(self, *args, **kwargs) -> Dict[str, Any]:
        return {"status": "ok", "tool": self.name, "args": args, "kwargs": kwargs}

    def validate(self, *args, **kwargs) -> Dict[str, Any]:
        return {"valid": True, "tool": self.name}

    def create_directory(self, path: str) -> str:
        location = Path(path)
        location.mkdir(parents=True, exist_ok=True)
        return str(location)

    def write_text_file(self, path: str, content: str, encoding: str = "utf-8") -> Dict[str, Any]:
        location = Path(path)
        location.parent.mkdir(parents=True, exist_ok=True)
        location.write_text(content, encoding=encoding)
        return {"success": True, "path": str(location), "bytes_written": len(content.encode(encoding))}

    def append_text_file(self, path: str, content: str, encoding: str = "utf-8") -> Dict[str, Any]:
        location = Path(path)
        location.parent.mkdir(parents=True, exist_ok=True)
        with location.open("a", encoding=encoding) as handle:
            handle.write(content)
        return {"success": True, "path": str(location), "bytes_written": len(content.encode(encoding))}

    def read_text_file(self, path: str, encoding: str = "utf-8") -> str:
        return Path(path).read_text(encoding=encoding)

    def list_directory(self, path: str) -> List[str]:
        return [str(item) for item in Path(path).iterdir()]

    def ensure_project_structure(self, root: str, files: dict[str, str]) -> Dict[str, Any]:
        ensure_directory(root)
        written = []
        for relative_path, content in files.items():
            full_path = Path(root) / relative_path
            full_path.parent.mkdir(parents=True, exist_ok=True)
            full_path.write_text(content, encoding="utf-8")
            written.append(str(full_path))
        return {"success": True, "root": root, "written": written}

    def create_python_project_files(self, root: str, app_name: str) -> Dict[str, Any]:
        files = {
            "README.md": f"# {app_name}\n\nGenerated by Telewhat.\n",
            "requirements.txt": "requests>=2.32.0\n",
            "main.py": "print('hello from telewhat')\n",
            "app/__init__.py": "",
            "app/main.py": "print('app package working')\n",
        }
        return self.ensure_project_structure(root, files)
